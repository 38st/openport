namespace openport::server {

/// Where a print traded against the option's quote when it arrived: at the bid
/// or the ask (within half a cent), between them, outside them, or with no
/// two-sided quote to compare with.
enum class PrintSide : std::uint8_t { Bid, Ask, Mid, Outside, Unquoted };
[[nodiscard]] std::string_view to_string(PrintSide side) noexcept;
[[nodiscard]] std::optional<PrintSide> parse_print_side(std::string_view text) noexcept;

/// One option trade on the tape.
struct FlowPrint {
  std::uint64_t sequence = 0;  ///< arrival order across the tape, from 1
  md::Timestamp time = 0;      ///< the provider's trade time
  std::string symbol;          ///< padded OSI
  std::string underlying;
  std::string expiry;          ///< expiry id, as the chain names it: "2026-10-16AM"
  double strike = 0;
  pricing::OptionType type = pricing::OptionType::Call;
  double multiplier = 100;
  double price = 0;
  double size = 0;
  /// The quote it was classified against; NaN without one.
  double bid = 0;
  double ask = 0;
  md::Timestamp quote_time = 0;
  PrintSide side = PrintSide::Unquoted;
  /// +1 when it lifted the ask or printed above it, -1 when it hit the bid or
  /// printed below it, 0 between them or unquoted.
  int direction = 0;
  std::uint16_t venue = 0;  ///< md::OptionTrade::venue; zero when unknown
  bool sweep = false;
  bool block = false;
  std::uint64_t group = 0;  ///< best-effort multi-leg group; zero when none
  bool simulated = false;   ///< generated by the demo market, not a market print

  [[nodiscard]] double premium() const noexcept { return price * size * multiplier; }
};

/// A bounded tape of option prints per underlying, for time and sales and flow.
/// The engine thread adds prints as they arrive; readers on other threads copy a
/// snapshot. Thread-safe.
///
/// Classification uses the quote the chain book holds when the print is applied.
/// The event queue coalesces quotes under load, so that quote can be a little
/// newer than the trade. Sweeps and multi-leg groups are inferred, not reported
/// by the feed:
/// - a sweep is two or more prints of one contract, in one direction, on at least
///   two known venues within `sweep_window` of each other;
/// - a block is a single print of at least `block_size` contracts;
/// - a multi-leg group is prints of different contracts of one underlying, on
///   the same venue (or none known), within `leg_window`, whose sizes are in a
///   whole ratio of at most 4:1. It can join unrelated prints and miss real spreads.
///   Simulated prints are never grouped.
class FlowTape {
 public:
  struct Options {
    std::size_t capacity = 5000;  ///< prints kept per underlying; the oldest go first
    double block_size = 100;      ///< contracts
    md::Timestamp sweep_window = md::kNanosPerSecond;
    md::Timestamp leg_window = md::kNanosPerSecond / 1000;
  };
  struct Snapshot {
    std::vector<FlowPrint> prints;  ///< oldest first
    std::uint64_t total = 0;        ///< prints ever added for the underlying
    std::uint64_t evicted = 0;      ///< of those, dropped for capacity
    bool simulated = false;         ///< any retained print is simulated
  };

  FlowTape() : FlowTape(Options{}) {}
  explicit FlowTape(Options options);

  /// Classifies `trade` against `option`'s current quote and appends it. Prints
  /// without a positive finite price and size are ignored.
  void add(const md::OptionTrade& trade, const analytics::OptionState& option, bool simulated = false);
  [[nodiscard]] Snapshot snapshot(const std::string& underlying) const;
  [[nodiscard]] const Options& options() const noexcept { return options_; }

 private:
  struct Tape {
    std::deque<FlowPrint> prints;
    std::uint64_t total = 0;
    std::uint64_t evicted = 0;
  };
  void mark_sweep(Tape& tape);
  void mark_legs(Tape& tape);

  Options options_;
  mutable std::mutex mutex_;
  std::map<std::string, Tape> tapes_;
  std::uint64_t sequence_ = 0;
  std::uint64_t groups_ = 0;
};

/// Expiry id of a contract, as the chain names its slice: the date, AM or PM
/// settlement, and -OEX or -XEO for those roots.
[[nodiscard]] std::string contract_expiry_id(const md::OptionContract& contract);

/// The demo market publishes cumulative volume, not trades. When the volume of
/// a contract rises by `increment` contracts, this picks a simulated print at its
/// current bid, ask or midpoint, deterministically from the contract and time.
/// nullopt without a two-sided quote. Never used for a market-data feed.
[[nodiscard]] std::optional<md::OptionTrade> simulated_print(const md::OptionVolume& volume,
    const analytics::OptionState& option, double increment);

}  // namespace openport::server
